// Draft: minimal generators for V2 exports. Pure functions, no library, all run in the browser
// (static demo included). Input "tc" = a saved API test case:
//   {name, method, url, headers:[[k,v]], body, checks:[{type:'status'|'json'|'time'|'contains', path?, expected}]}
// Secrets: exporters replace Authorization / x-api-key values with {{token}} unless keepSecrets=true.

const SECRET = /^(authorization|x-api-key|api-key|cookie|proxy-authorization)$/i;
const scrub = (headers, keep) => headers.filter(([k]) => k).map(([k, v]) =>
  [k, keep || !SECRET.test(k) ? v : (/^bearer /i.test(v) ? 'Bearer {{token}}' : '{{token}}')]);
const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`; // POSIX single-quote

// ---- curl ---------------------------------------------------------------
function toCurl(tc, keep = false) {
  const parts = [`curl -sS -X ${tc.method} ${shq(tc.url)}`];
  for (const [k, v] of scrub(tc.headers, keep)) parts.push(`-H ${shq(`${k}: ${v}`)}`);
  if (tc.body) parts.push(`--data-raw ${shq(tc.body)}`);
  return parts.join(' \\\n  ');
}

// ---- Postman Collection v2.1 -------------------------------------------
// Schema: https://schema.getpostman.com/json/collection/v2.1.0/collection.json
// "auth" kept as headers (simplest, imports cleanly). Checks become pm.test scripts.
function pmTests(checks) {
  return checks.map((c) => {
    if (c.type === 'status') return `pm.test("Status is ${c.expected}", () => pm.response.to.have.status(${Number(c.expected)}));`;
    if (c.type === 'time') return `pm.test("Responds under ${c.expected} ms", () => pm.expect(pm.response.responseTime).to.be.below(${Number(c.expected) + 1}));`;
    if (c.type === 'contains') return `pm.test("Body contains ${c.expected}", () => pm.expect(pm.response.text()).to.include(${JSON.stringify(c.expected)}));`;
    const p = c.path.replace(/^\$\.?/, '');
    return `pm.test("${p} = ${c.expected}", () => pm.expect(String(pm.response.json().${p})).to.eql(${JSON.stringify(String(c.expected))}));`;
  });
}
function toPostman(name, cases, keep = false) {
  return {
    info: { _postman_id: crypto.randomUUID(), name,
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json' },
    item: cases.map((tc) => ({
      name: tc.name,
      request: {
        method: tc.method,
        header: scrub(tc.headers, keep).map(([key, value]) => ({ key, value, type: 'text' })),
        ...(tc.body && { body: { mode: 'raw', raw: tc.body, options: { raw: { language: 'json' } } } }),
        url: tc.url, // a raw string is valid v2.1; Postman parses host/path/query on import
      },
      event: tc.checks?.length ? [{ listen: 'test', script: { type: 'text/javascript', exec: pmTests(tc.checks) } }] : [],
    })),
    variable: keep ? [] : [{ key: 'token', value: '' }],
  };
}

// ---- pytest + requests --------------------------------------------------
const py = (v) => JSON.stringify(v); // JSON string literal is a valid Python str literal for our content
function toPytest(cases, keep = false) {
  const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '') || 'case';
  const out = ['"""Generated by Analyst Kit. Run: pip install requests pytest && pytest -q"""',
    'import os', '', 'import requests', '', 'TOKEN = os.environ.get("API_TOKEN", "")', ''];
  for (const tc of cases) {
    const hdr = scrub(tc.headers, keep).map(([k, v]) =>
      `        ${py(k)}: ${v.includes('{{token}}') ? `${py(v.split('{{token}}')[0])} + TOKEN` : py(v)},`);
    out.push(`def test_${slug(tc.name)}():`,
      `    r = requests.request(`, `        ${py(tc.method)},`, `        ${py(tc.url)},`,
      `        headers={`, ...hdr.map((l) => '    ' + l), `        },`,
      ...(tc.body ? [`        data=${py(tc.body)}.encode("utf-8"),`] : []),
      `        timeout=30,`, `    )`);
    for (const c of tc.checks || []) {
      if (c.type === 'status') out.push(`    assert r.status_code == ${Number(c.expected)}, r.text`);
      if (c.type === 'time') out.push(`    assert r.elapsed.total_seconds() * 1000 <= ${Number(c.expected)}`);
      if (c.type === 'contains') out.push(`    assert ${py(c.expected)} in r.text`);
      if (c.type === 'json') {
        const keys = c.path.replace(/^\$\.?/, '').split(/\.|\[(\d+)\]/).filter(Boolean)
          .map((k) => (/^\d+$/.test(k) ? `[${k}]` : `[${py(k)}]`)).join('');
        out.push(`    assert str(r.json()${keys}) == ${py(String(c.expected))}`);
      }
    }
    out.push('', '');
  }
  return out.join('\n');
}

// ---- CSV helper (RFC 4180; BOM so Excel opens UTF-8 French text correctly) ----
const csvCell = (v) => { const s = v == null ? '' : String(v); return /[",\n\r;]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
const toCsv = (rows) => '﻿' + rows.map((r) => r.map(csvCell).join(',')).join('\r\n');

// ---- Jira CSV (Jira Cloud "External system import" -> CSV; map columns in the wizard) ----
// Stories: Summary, Issue Type, Description, Priority, Labels (repeat column for several), Epic Link / Parent,
// Story Points, Acceptance Criteria goes into Description (custom fields differ per site).
function toJiraCsv(stories) {
  const rows = [['Summary', 'Issue Type', 'Description', 'Priority', 'Labels', 'Labels', 'Story Points', 'Parent']];
  for (const s of stories) rows.push([s.title, s.type || 'Story',
    `${s.story}\n\n*Acceptance criteria*\n${(s.criteria || []).map((c) => '# ' + c).join('\n')}`,
    s.priority || 'Medium', s.labels?.[0] || '', s.labels?.[1] || '', s.points ?? '', s.parent || '']);
  return toCsv(rows);
}

// ---- Xray ---------------------------------------------------------------
// (a) Xray Test Case Importer CSV (Cloud + DC): one row per step, rows sharing "Test ID" form one test.
function toXrayCsv(tests) {
  const rows = [['Test ID', 'Summary', 'Test Type', 'Priority', 'Labels', 'Action', 'Data', 'Expected Result']];
  tests.forEach((t, i) => (t.steps.length ? t.steps : [{}]).forEach((st, j) => rows.push(
    [i + 1, j ? '' : t.summary, j ? '' : 'Manual', j ? '' : (t.priority || 'Medium'), j ? '' : (t.labels || []).join(' '),
      st.action || '', st.data || '', st.result || ''])));
  return toCsv(rows);
}
// (b) Xray Cloud REST v2 bulk import JSON: POST https://xray.cloud.getxray.app/api/v2/import/test/bulk
//     Manual tests carry "steps"; Cucumber tests carry "gherkin_def"; Generic carry "unstructured_def".
function toXrayJson(tests, projectKey) {
  return tests.map((t) => t.gherkin
    ? { testtype: 'Cucumber', fields: { summary: t.summary, project: { key: projectKey }, labels: t.labels || [] }, gherkin_def: t.gherkin }
    : { testtype: 'Manual', fields: { summary: t.summary, project: { key: projectKey }, labels: t.labels || [] },
        steps: t.steps.map(({ action, data = '', result = '' }) => ({ action, data, result })) });
}

// ---- Gherkin .feature ---------------------------------------------------
// FR samples: "# language: fr" + Fonctionnalité / Scénario / Soit / Quand / Alors / Et.
const KW = { en: ['Feature', 'Scenario', 'Given', 'When', 'Then', 'And', 'Background'],
             fr: ['Fonctionnalité', 'Scénario', 'Soit', 'Quand', 'Alors', 'Et', 'Contexte'] };
function toFeature(feature, lang = 'en') {
  const [F, S, G, W, T, A] = KW[lang];
  const out = lang === 'fr' ? ['# language: fr'] : [];
  out.push(`${F}: ${feature.name}`, ...(feature.description ? ['  ' + feature.description] : []), '');
  for (const sc of feature.scenarios) {
    out.push(...(sc.tags?.length ? ['  ' + sc.tags.map((t) => '@' + t).join(' ')] : []), `  ${S}: ${sc.name}`);
    const block = (kw, list) => list?.forEach((line, i) => out.push(`    ${i ? A : kw} ${line}`));
    block(G, sc.given); block(W, sc.when); block(T, sc.then); out.push('');
  }
  return out.join('\n');
}

// ---- Download helper ----------------------------------------------------
function download(name, text, type = 'text/plain') {
  const a = Object.assign(document.createElement('a'), { href: URL.createObjectURL(new Blob([text], { type })), download: name });
  document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

