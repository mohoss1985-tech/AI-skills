#!/usr/bin/env python3
"""Check a source-to-target mapping file and generate reconciliation and data quality SQL.

Usage:
  python3 check_mapping.py mapping.csv --key arn [--dialect postgres|sqlserver|oracle]
                           [--rules rules.csv] > checks.sql

mapping.csv columns: target_table, target_field, type, mandatory (Y/N), source_table, source_field,
transformation, default, rule, allowed (optional, values separated by |).
--key is the target field that identifies a record; its source field comes from the mapping.
Mapping defects go to stderr; the SQL goes to stdout. Exit code 1 if there are errors.
"""
import argparse
import csv
import re
import sys
from collections import Counter, defaultdict

LEN = {"postgres": "LENGTH", "oracle": "LENGTH", "sqlserver": "LEN"}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mapping")
    ap.add_argument("--key", required=True)
    ap.add_argument("--dialect", default="postgres", choices=sorted(LEN))
    ap.add_argument("--rules", help="CSV with an 'id' column listing the data quality rules (DQ-01…)")
    a = ap.parse_args()
    length = LEN[a.dialect]

    with open(a.mapping, newline="", encoding="utf-8-sig") as f:
        rows = [{k.strip().lower(): (v or "").strip() for k, v in r.items() if k} for r in csv.DictReader(f)]
    rule_ids = None
    if a.rules:
        with open(a.rules, newline="", encoding="utf-8-sig") as f:
            rule_ids = {(r.get("id") or "").strip() for r in csv.DictReader(f)}

    errors, warnings = [], []
    seen = Counter((r["target_table"], r["target_field"]) for r in rows)
    for (t, fld), n in seen.items():
        if n > 1:
            errors.append(f"{t}.{fld}: mapped {n} times")
    for r in rows:
        name = f"{r['target_table']}.{r['target_field']}"
        mand = r.get("mandatory", "").upper() in ("Y", "YES", "O", "OUI", "TRUE", "1")
        r["_mand"] = mand
        has_src = bool(r.get("source_field")) or bool(r.get("transformation"))
        if not r.get("type"):
            errors.append(f"{name}: no type")
        if mand and not has_src and not r.get("default"):
            errors.append(f"{name}: mandatory but no source, transformation or default")
        elif not has_src and not r.get("default"):
            warnings.append(f"{name}: not mapped (will stay empty)")
        elif mand and has_src and not r.get("default") and "COALESCE" not in r.get("transformation", "").upper():
            warnings.append(f"{name}: mandatory, no default: records with an empty {r.get('source_field') or 'source'} will be rejected")
        if rule_ids is not None and r.get("rule"):
            for rid in re.split(r"[;, ]+", r["rule"]):
                if rid and rid not in rule_ids:
                    errors.append(f"{name}: rule {rid} is not in {a.rules}")
        if r.get("allowed") and not r.get("default") and not r.get("transformation"):
            warnings.append(f"{name}: has allowed values but no translation: check every source code is valid")

    by_table = defaultdict(list)
    for r in rows:
        by_table[r["target_table"]].append(r)

    for m in errors:
        print("ERROR   " + m, file=sys.stderr)
    for m in warnings:
        print("WARNING " + m, file=sys.stderr)
    print(f"{len(rows)} fields in {len(by_table)} table(s): {len(errors)} error(s), {len(warnings)} warning(s).", file=sys.stderr)

    out = [f"-- Generated by check_mapping.py from {a.mapping} ({a.dialect}). Review before running.",
           "-- Each query returns one row per check; a non-zero 'failing' value needs a look.\n"]
    for t, fields in by_table.items():
        src_tables = Counter(r["source_table"] for r in fields if r.get("source_table"))
        src = src_tables.most_common(1)[0][0] if src_tables else None
        key = next((r for r in fields if r["target_field"] == a.key), None)
        out.append(f"-- ===== {t} =====")
        if src:
            out.append(f"-- 1. Row counts: source {src} vs target {t} (the difference should match the rejection report)")
            out.append(f"SELECT (SELECT COUNT(*) FROM {src}) AS source_rows, (SELECT COUNT(*) FROM {t}) AS target_rows;\n")
        if key and src and key.get("source_field"):
            sk = key["source_field"]
            out.append(f"-- 2. Key reconciliation on {a.key} (source {src}.{sk})")
            if key.get("transformation"):
                out.append(f"--    The key is transformed ({key['transformation']}): apply the same transformation to s.{sk} below.")
            out.append(f"SELECT 'missing in target' AS check_name, COUNT(*) AS failing FROM {src} s\n"
                       f"  WHERE NOT EXISTS (SELECT 1 FROM {t} t WHERE t.{a.key} = s.{sk})\n"
                       f"UNION ALL\nSELECT 'not in source', COUNT(*) FROM {t} t\n"
                       f"  WHERE NOT EXISTS (SELECT 1 FROM {src} s WHERE s.{sk} = t.{a.key})\n"
                       f"UNION ALL\nSELECT 'duplicate key in target', COUNT(*) - COUNT(DISTINCT {a.key}) FROM {t};\n")
        elif key is None:
            out.append(f"-- 2. Key reconciliation skipped: {a.key} is not a target field of {t}\n")
        checks = []
        for r in fields:
            f_ = r["target_field"]
            if r["_mand"]:
                checks.append((f"{f_} mandatory", f"{f_} IS NULL OR TRIM(CAST({f_} AS VARCHAR(4000))) = ''", r.get("rule", "")))
            m = re.match(r"(?:var)?char\((\d+)\)", r.get("type", "").lower())
            if m:
                checks.append((f"{f_} longer than {m.group(1)}", f"{length}({f_}) > {m.group(1)}", r.get("rule", "")))
            if r.get("allowed"):
                vals = ", ".join(q(v.strip()) for v in r["allowed"].split("|"))
                checks.append((f"{f_} not in allowed values", f"{f_} IS NOT NULL AND {f_} NOT IN ({vals})", r.get("rule", "")))
            if "email" in f_.lower():
                checks.append((f"{f_} invalid email", f"{f_} IS NOT NULL AND {f_} NOT LIKE '%_@_%._%'", r.get("rule", "")))
            if "iban" in f_.lower():
                checks.append((f"{f_} invalid IBAN shape", f"{f_} IS NOT NULL AND ({length}({f_}) NOT BETWEEN 15 AND 34 "
                               f"OR {f_} <> UPPER({f_}) OR {f_} LIKE '% %')", r.get("rule", "")))
        if checks:
            out.append(f"-- 3. Data quality checks on {t}")
            out.append("SELECT check_name, rule, failing FROM (\n" + "\nUNION ALL\n".join(
                f"  SELECT {q(n)} AS check_name, {q(rule)} AS rule, SUM(CASE WHEN {cond} THEN 1 ELSE 0 END) AS failing FROM {t}"
                for n, cond, rule in checks) + "\n) c ORDER BY failing DESC;\n")
    print("\n".join(out))
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
